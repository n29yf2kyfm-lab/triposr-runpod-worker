def format_report(plan):
    p = plan
    L = []
    L.append("=" * 78)
    L.append(f"corpus          {p['root']}")
    L.append(f"seed            {p['seed']}   unit={p['unit']}   "
             f"target={p['target_per_class']}   max_repeat={p['max_repeat']}")
    st = p["ingest"]
    L.append(f"coco files      {st['coco_files']}")
    L.append(f"originals       {p['n_originals']} unique "
             f"(seen {st['images_seen']}, dup sha {st['duplicate_shas']}, "
             f"missing file {st['images_missing_file']}, "
             f"no usable boxes {st['images_no_boxes']})")
    L.append(f"boxes           {p['n_boxes']} kept of {st['boxes_seen']} "
             f"(bad {st['boxes_dropped_bad']}, "
             f"untrained class {st['boxes_dropped_untrained']})")
    if st["untrained_categories"]:
        L.append(f"                untrained categories: "
                 f"{sorted(st['untrained_categories'])}")
    L.append("")
    L.append("SPLIT (originals only, 80/10/10, stratified by rarest class "
             "present)")
    L.append(f"  {'class':<16}{'total':>7}{'train':>8}{'valid':>8}{'test':>7}")
    for cls in sorted(p["split_by_owner"]):
        s = p["split_by_owner"][cls]
        L.append(f"  {cls:<16}{s['total']:>7}{s['train']:>8}"
                 f"{s['valid']:>8}{s['test']:>7}")
    tot = p["split_totals"]
    L.append(f"  {'ALL':<16}{tot['total']:>7}{tot['train']:>8}"
             f"{tot['valid']:>8}{tot['test']:>7}")
    L.append("")
    L.append(f"BALANCE (train split only; valid and test stay real and "
             f"un-augmented). Unit: {p['unit']}.")
    L.append(f"  {'class':<16}{'real':>9}{'target':>9}{'achieved':>10}"
             f"{'eff x':>8}{'req x':>8}{'imgs':>7}{'maxrep':>8}  flag")
    for cls in sorted(p["balance"]):
        b = p["balance"][cls]
        flag = ("UNHEALTHY" if b["unhealthy"] else
                "capped" if b["capped_by_max_repeat"] else
                "ok" if b["reached_target"] else "short")
        L.append(f"  {cls:<16}{b['real']:>9}{b['target']:>9}"
                 f"{b['achieved']:>10}{b['effective_multiplier']:>8.2f}"
                 f"{b['required_multiplier']:>8.2f}{b['train_images']:>7}"
                 f"{b['max_repeat_used']:>8}  {flag}")
    L.append("")
    L.append(f"train samples   {p['n_samples']['train']} "
             f"({p['n_samples']['train_originals']} originals + "
             f"{p['n_samples']['train_augmented']} augmented repeats)")
    L.append(f"valid samples   {p['n_samples']['valid']}  (0 augmented)")
    L.append(f"test samples    {p['n_samples']['test']}  (0 augmented)")
    if p["flags"]:
        L.append("")
        L.append("FLAGS")
        for fl in p["flags"]:
            L.append(f"  ! {fl}")
    else:
        L.append("")
        L.append("FLAGS           none — every class reached target within "
                 "the multiplier ceiling.")
    L.append("=" * 78)
    return "\n".join(L)


# ------------------------------------------------------------------ build ---

def load_train_only(path):
    """Read a train-only pin list: bare shas, or jsonl rows with a `sha`.

    Also accepts clean_dataset's own cache format, keeping only the verdicts
    whose policy is "train_only" — so the output of the cleaning pass can be
    handed straight in without an intermediate conversion step.
    """
    if not path:
        return set()
    try:
        from clean_dataset import policy_for
    except Exception:                                       # pragma: no cover
        def policy_for(_v):
            return "train_only"
    out = set()
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            if line.startswith("{"):
                try:
                    r = json.loads(line)
                except ValueError:
                    continue
                sha = r.get("sha")
                if sha and ("verdict" not in r
                            or policy_for(r["verdict"]) == "train_only"):
                    out.add(sha)
            else:
                out.add(line.split()[0])
    return out


def build(root, out_dir, target_per_class=None, max_repeat=15, seed=1337,
          unit="boxes", unhealthy=UNHEALTHY_MULTIPLIER, sha_cache=None,
          report_only=False, verbose=True, train_only=None,
          merge_groups=False):
    """Do the whole thing. Returns (plan, samples, images)."""
    global GROUPED
    GROUPED = bool(merge_groups)
    root = os.path.abspath(root)
    images, stats = load_originals(root, sha_cache, verbose)
    if not images:
        raise SystemExit(f"no usable images found under {root}")

    split_by_owner, global_box_counts = split_originals(images, seed,
                                                       train_only)

    train_recs = [r for r in images if r["split"] == "train"]
    real_train = count_units(train_recs, {r["sha"]: 1 for r in train_recs}, unit)
    if target_per_class is None:
        # Default: level up to whatever the largest class already has, which is
        # the only target that needs no extra data by definition.
        target_per_class = max(real_train.values()) if real_train else 0

    reps, balance, flags = balance_train(train_recs, target_per_class,
                                         max_repeat, unit, unhealthy)
    samples = build_samples(images, reps)

    n_train = sum(1 for s in samples if s["split"] == "train")
    n_train_orig = sum(1 for s in samples
                       if s["split"] == "train" and s["rep"] == 0)
    plan = {
        "root": root,
        "seed": seed,
        "unit": unit,
        "target_per_class": target_per_class,
        "max_repeat": max_repeat,
        "unhealthy_multiplier": unhealthy,
        "recipes": [list(r) for r in RECIPES],
        "box_safe_ops": list(BOX_SAFE_OPS),
        "excluded_ops": ["rotate (inflates boxes on re-fit — see docstring)"],
        "ingest": stats,
        "n_originals": len(images),
        "n_boxes": sum(len(r["boxes"]) for r in images),
        "corpus_boxes_by_class": global_box_counts,
        "split_by_owner": split_by_owner,
        "split_totals": {
            "total": len(images),
            "train": sum(1 for r in images if r["split"] == "train"),
            "valid": sum(1 for r in images if r["split"] == "valid"),
            "test": sum(1 for r in images if r["split"] == "test"),
        },
        "balance": balance,
        "flags": flags,
        "n_samples": {
            "train": n_train,
            "train_originals": n_train_orig,
            "train_augmented": n_train - n_train_orig,
            "valid": sum(1 for s in samples if s["split"] == "valid"),
            "test": sum(1 for s in samples if s["split"] == "test"),
        },
    }

    if not report_only:
        write_outputs(out_dir, samples, images,
                      classes_document(global_box_counts, images), plan)
    return plan, samples, images


# --------------------------------------------------------------- selftest ---

def _dir_digest(d):
    out = {}
    for fn in sorted(os.listdir(d)):
        p = os.path.join(d, fn)
        if os.path.isfile(p):
            out[fn] = sha256_file(p)
    return out


def selftest(root, target_per_class=None, max_repeat=15, seed=1337,
             unit="boxes"):
    """Check the guarantees rather than claim them. Returns True if all pass."""
    import shutil
    import tempfile

    results = []

    def check(name, ok, detail=""):
        results.append((name, bool(ok), detail))
        print(f"  [{'PASS' if ok else 'FAIL'}] {name}"
              f"{('  — ' + detail) if detail else ''}")

    tmp = tempfile.mkdtemp(prefix="train_index_selftest_")
    try:
        a = os.path.join(tmp, "a")
        b = os.path.join(tmp, "b")
        print("selftest: building twice with the same seed ...")
        plan, samples, images = build(root, a, target_per_class, max_repeat,
                                      seed, unit, verbose=False)
        build(root, b, target_per_class, max_repeat, seed, unit, verbose=False)

        # 1. every original in exactly one split
        splits = {}
        for rec in images:
            splits.setdefault(rec["split"], set()).add(rec["sha"])
        union = set()
        overlap = set()
        for s, shas in splits.items():
            overlap |= (union & shas)
            union |= shas
        check("every original appears in exactly one split",
              not overlap and union == {r["sha"] for r in images},
              f"{len(images)} originals, {len(overlap)} in two splits")

        # 2. no sha shared between splits (the leak that produced 0.4390 mAP)
        by_split = {}
        for s in samples:
            by_split.setdefault(s["split"], set()).add(s["sha"])
        cross = ((by_split.get("train", set()) & by_split.get("valid", set()))
                 | (by_split.get("train", set()) & by_split.get("test", set()))
                 | (by_split.get("valid", set()) & by_split.get("test", set())))
        check("no sha appears in more than one split (incl. repeats)",
              not cross, f"{len(cross)} leaked shas")

        # 3. valid and test carry zero augmented entries and zero repeats
        bad_aug = [s for s in samples
                   if s["split"] in ("valid", "test")
                   and (s["recipe"] or s["rep"] != 0)]
        seen = {}
        dupes = 0
        for s in samples:
            if s["split"] in ("valid", "test"):
                k = (s["split"], s["sha"])
                dupes += 1 if k in seen else 0
                seen[k] = 1
        check("valid and test contain zero augmented entries",
              not bad_aug and not dupes,
              f"{len(bad_aug)} augmented, {dupes} repeated")

        # 4. class distribution after balancing matches the target
        bad = []
        for cls, row in plan["balance"].items():
            if row["reached_target"]:
                continue
            # Falling short is only acceptable if the plan SAYS so.
            if not (row["capped_by_max_repeat"] or row["unhealthy"]):
                bad.append(cls)
        check("class distribution reaches target, or is flagged when it "
              "cannot", not bad, f"unexplained shortfalls: {bad or 'none'}")

        # 4b. the achieved numbers are real, recomputed from the emitted index
        counts = {}
        by_sha = {r["sha"]: r for r in images}
        for s in samples:
            if s["split"] != "train":
                continue
            for c, n in by_sha[s["sha"]]["counts"].items():
                counts[c] = counts.get(c, 0) + (n if unit == "boxes" else 1)
        mismatch = {c: (counts.get(c, 0), plan["balance"][c]["achieved"])
                    for c in plan["balance"]
                    if counts.get(c, 0) != plan["balance"][c]["achieved"]}
        check("reported achieved counts match the emitted index",
              not mismatch, str(mismatch or "exact"))

        # 4c. THE DECORRELATION PROPERTY. Synthetic watermarks only neutralise
        #     the real ones if they land on every class at the SAME rate; a
        #     skewed stamp would create exactly the shortcut it is meant to
        #     destroy. Measured per class against WM_RATE, not assumed.
        wm_by_cls, n_by_cls = {}, {}
        for s in samples:
            if s["split"] != "train":
                continue
            for c in by_sha[s["sha"]]["counts"]:
                n_by_cls[c] = n_by_cls.get(c, 0) + 1
                wm_by_cls[c] = wm_by_cls.get(c, 0) + (1 if s["wm"] else 0)
        skew = {}
        for c, n in n_by_cls.items():
            if n < 200:                    # too few to bound meaningfully
                continue
            rate = wm_by_cls[c] / n
            # 4 binomial sigma, so a correct build effectively never trips it
            tol = 4.0 * (WM_RATE * (1 - WM_RATE) / n) ** 0.5
            if abs(rate - WM_RATE) > max(tol, 0.02):
                skew[c] = round(rate, 4)
        rates = {c: round(wm_by_cls[c] / n, 3) for c, n in n_by_cls.items()}
        check(f"watermark rate is class-independent (target {WM_RATE}) {rates}",
              not skew, f"skewed: {skew}")

        # 4d. valid and test must carry no synthetic marks at all, or the
        #     score measures the augmentation rather than the model
        dirty = sum(1 for s in samples
                    if s["split"] != "train" and (s["wm"] or s["sn"]))
        check("valid and test carry zero synthetic marks", dirty == 0,
              f"{dirty} marked eval samples")

        # 4e. train_only pinning: images with a burned-in label must never
        #     reach valid or test, and pinning them must not shrink either.
        all_shas = sorted({r["sha"] for r in images})
        pin = set(all_shas[::7])                 # ~14% of the corpus
        import tempfile as _tf
        with _tf.TemporaryDirectory() as c:
            plan_p, samples_p, images_p = build(
                root, c, target_per_class, max_repeat, seed, unit,
                verbose=False, train_only=pin)
            leaked = [s["sha"] for s in samples_p
                      if s["split"] != "train" and s["sha"] in pin]
            check(f"pinned images never reach valid or test ({len(pin)} pinned)",
                  not leaked, f"{len(leaked)} leaked")
            sz = {k: sum(1 for r in images_p if r["split"] == k)
                  for k in ("train", "valid", "test")}
            sz0 = {k: sum(1 for r in images if r["split"] == k)
                   for k in ("train", "valid", "test")}
            check(f"pinning leaves split sizes unchanged {sz}",
                  sz == sz0, f"{sz} vs {sz0}")
            evalpool = [s for s in samples_p if s["split"] in ("valid", "test")]
            check("eval pool is still non-empty after pinning",
                  len(evalpool) > 0, f"{len(evalpool)}")

        # 4f. --merge-groups must build end to end and stay self-consistent.
        #     It did not: write_outputs re-derived the class index from
        #     class_map instead of taking it from classes.json, so a grouped
        #     build died on KeyError 'surface' AFTER writing a complete
        #     index.jsonl — the failure mode that leaves a half-written output
        #     directory looking plausible.
        with _tf.TemporaryDirectory() as gdir:
            gplan, gsamples, gimages = build(
                root, gdir, target_per_class, max_repeat, seed, unit,
                verbose=False, merge_groups=True)
            with open(os.path.join(gdir, "classes.json")) as fh:
                gcls = json.load(fh)
            names = {r["name"] for r in gcls["classes"]}
            check(f"--merge-groups writes the group vocabulary {sorted(names)}",
                  names == set(CM.TRAIN_GROUPS), str(sorted(names)))
            wrote = sorted(os.listdir(gdir))
            check(f"--merge-groups writes all four outputs {wrote}",
                  wrote == ["classes.json", "images.jsonl", "index.jsonl",
                            "plan.json"], str(wrote))
            valid_ids = set(gcls["name_to_index"].values())
            bad = 0
            with open(os.path.join(gdir, "images.jsonl")) as fh:
                for ln in fh:
                    for bb in json.loads(ln)["boxes"]:
                        if bb[0] not in valid_ids:
                            bad += 1
            check("grouped box class ids all appear in classes.json",
                  bad == 0, f"{bad} unknown ids")
            gowners = {r["owner"] for r in gimages}
            check("grouped owners are group names",
                  gowners <= set(CM.TRAIN_GROUPS), str(sorted(gowners)))
            # grouping must not lose or invent boxes
            n_un = sum(len(r["boxes"]) for r in images)
            n_gr = sum(len(r["boxes"]) for r in gimages)
            check(f"grouping preserves the box count ({n_gr} vs {n_un})",
                  n_gr == n_un, f"{n_gr} vs {n_un}")

        # 5. byte-identical reruns
        da, db = _dir_digest(a), _dir_digest(b)
        check("two runs with the same seed are byte-identical",
              da == db and len(da) == 4,
              f"{len(da)} files: {sorted(da)}")

        # 6. every original used once before any is used twice
        first_aug = next((i for i, s in enumerate(samples)
                          if s["split"] == "train" and s["rep"] > 0), None)
        n_orig = plan["n_samples"]["train_originals"]
        check("every original is emitted once before any is emitted twice",
              first_aug is None or first_aug == n_orig,
              f"first augmented sample at position {first_aug} of "
              f"{n_orig} originals")

        # 7. only box-safe ops, and no rotation anywhere
        ops = set()
        for s in samples:
            ops |= set(s["recipe"])
        check("only box-safe augmentation ops appear (no rotation)",
              ops <= set(BOX_SAFE_OPS) and not any("rot" in o for o in ops),
              f"ops used: {sorted(ops)}")

        # 8. the index points at files that exist
        missing = [s["file"] for s in samples[:2000]
                   if not os.path.isfile(os.path.join(plan["root"], s["file"]))]
        check("index paths resolve to real files",
              not missing, f"{len(missing)} missing")

        # 9. classes.json carries index / colour / canonical from class_map
        with open(os.path.join(a, "classes.json")) as f:
            cdoc = json.load(f)
        idx = CM.class_index()
        ok = all(r["index"] == idx[r["name"]]
                 and r["colour"] == CM.colour(r["name"])
                 and r["canonical"] == CM.canonical(r["name"])
                 for r in cdoc["classes"]) and 0 not in idx.values()
        check("classes.json matches class_map (index>=1, colour, canonical)",
              ok, f"{len(cdoc['classes'])} classes, index 0 reserved")

        # 10. --report-only writes nothing
        empty = os.path.join(tmp, "empty")
        build(root, empty, target_per_class, max_repeat, seed, unit,
              report_only=True, verbose=False)
        check("--report-only writes nothing", not os.path.exists(empty))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    n_fail = sum(1 for _n, ok, _d in results if not ok)
    print(f"\nselftest: {len(results) - n_fail}/{len(results)} passed")
    return n_fail == 0


# ------------------------------------------------------------------- main ---

def main():
    ap = argparse.ArgumentParser(
        description="Split-then-balance a COCO damage corpus into a training "
                    "INDEX (no pixels are copied).")
    ap.add_argument("--coco", required=True,
                    help="corpus root; every _annotations.coco.json beneath "
                         "it is pooled and the upstream split is discarded")
    ap.add_argument("--out", default=None,
                    help="output directory for index.jsonl, images.jsonl, "
                         "classes.json, plan.json")
    ap.add_argument("--target-per-class", type=int, default=None,
                    help="per-class target in the train split; default is the "
                         "largest class's real count")
    ap.add_argument("--max-repeat", type=int, default=15,
                    help="hard ceiling on how many times one original may be "
                         "used in train (default 15)")
    ap.add_argument("--unit", choices=("boxes", "images"), default="boxes",
                    help="count the target in annotation boxes (default) or "
                         "in images")
    ap.add_argument("--seed", type=int, default=1337)
    ap.add_argument("--merge-groups", action="store_true",
                    help="fold FINAL_CLASSES into class_map.TRAIN_GROUPS, so "
                         "balance comes from merging related damage rather "
                         "than from 15x cloning of the thin classes")
    ap.add_argument("--train-only-list",
                    help="file of shas (one per line, or jsonl with a 'sha' "
                         "field) barred from valid/test. Images with a "
                         "burned-in label: fine to train on, never to score "
                         "on. See clean_dataset.VERDICT_POLICY.")
    ap.add_argument("--unhealthy-multiplier", type=float,
                    default=UNHEALTHY_MULTIPLIER,
                    help="flag any class needing more than this multiplier "
                         "(default 15)")
    ap.add_argument("--sha-cache", default=None,
                    help="optional JSON cache of file SHAs, for large corpora "
                         "whose COCO has no `sha` field")
    ap.add_argument("--report-only", action="store_true",
                    help="print the plan and write nothing")
    ap.add_argument("--selftest", action="store_true",
                    help="check the split/balance guarantees on --coco")
    args = ap.parse_args()

    if args.selftest:
        ok = selftest(args.coco, args.target_per_class, args.max_repeat,
                      args.seed, args.unit)
        raise SystemExit(0 if ok else 1)

    if not args.report_only and not args.out:
        ap.error("--out is required unless --report-only is given")

    pin = load_train_only(args.train_only_list)
    if pin:
        print(f"train-only pins: {len(pin):,} shas barred from valid/test")

    plan, _samples, _images = build(
        args.coco, args.out, args.target_per_class, args.max_repeat,
        args.seed, args.unit, args.unhealthy_multiplier, args.sha_cache,
        report_only=args.report_only, train_only=pin,
        merge_groups=args.merge_groups)
    print(format_report(plan))
    if args.report_only:
        print("\n--report-only: nothing was written.")
    else:
        print(f"\nwrote index.jsonl images.jsonl classes.json plan.json "
              f"-> {os.path.abspath(args.out)}")


if __name__ == "__main__":
    main()
